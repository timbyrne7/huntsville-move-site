#!/usr/bin/env python3
"""Generate the search-engine surface for the Move to Huntsville site.

Idempotent: injects a marked block of head tags into every content page and
writes robots.txt + sitemap.xml from the pages that actually exist on disk, so
the sitemap can never drift from the site.

    python3 tools/gen_seo.py            # write tags, robots.txt, sitemap.xml
    python3 tools/gen_seo.py --check    # exit 1 if anything is out of date

Per page it emits: <link rel="canonical">, Open Graph, Twitter card, and JSON-LD
(WebSite + Organization on the index, WebPage + BreadcrumbList elsewhere).
Internal pages (logo-preview.html) get <meta name="robots" content="noindex">
instead and are kept out of the sitemap.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGIN = "https://www.movetohuntsville.net"
SITE_NAME = "Move to Huntsville"
OG_IMAGE = f"{ORIGIN}/assets/og.png"

START = "<!-- SEO:START (generated by tools/gen_seo.py — do not edit by hand) -->"
END = "<!-- SEO:END -->"

# Files that should never be indexed (internal preview/debug pages).
NOINDEX = {"logo-preview.html"}
# Priority + changefreq per page. Anything not listed gets the article defaults.
PRIORITY = {
    "index.html": ("1.0", "weekly"),
    "moving-to-huntsville.html": ("0.9", "monthly"),
    "neighborhoods.html": ("0.9", "monthly"),
    "schools.html": ("0.9", "monthly"),
    "commute.html": ("0.9", "monthly"),
    "cost-of-living.html": ("0.9", "monthly"),
    # prequal.html retired 2026-10-21 — it now redirects to the Google Business
    # Profile, so it stays out of the sitemap. Do not re-add.
    "rent-vs-buy.html": ("0.8", "monthly"),
    "rent-in-huntsville.html": ("0.8", "monthly"),
    "property-taxes.html": ("0.8", "monthly"),
    "redstone-arsenal-pcs-va-loans.html": ("0.8", "monthly"),
    "home-search.html": ("0.7", "monthly"),
    "huntsville-employers.html": ("0.7", "monthly"),
    "huntsville-crime-safety.html": ("0.7", "monthly"),
    "is-huntsville-a-good-place-to-live.html": ("0.7", "monthly"),
    "checklist.html": ("0.6", "monthly"),
    "local-realtors.html": ("0.6", "monthly"),
    "local-insurance.html": ("0.6", "monthly"),
    "about.html": ("0.4", "yearly"),
    "photos.html": ("0.2", "yearly"),
}
DEFAULT_PRIORITY = ("0.6", "monthly")

# Head tags this generator owns: removed before re-injecting, so the marked
# block is the only copy and hand-written og: tags can't shadow it.
OG_META = re.compile(
    r'[ \t]*<meta[^>]*(?:property|name)="(?:og|twitter):[^"]*"[^>]*>[ \t]*\r?\n?', re.I)
CANONICAL = re.compile(r'[ \t]*<link[^>]*rel="canonical"[^>]*>[ \t]*\r?\n?', re.I)
HEAD = re.compile(r"<head>.*?</head>", re.S)


def pages():
    """Content pages in a stable, priority-first order."""
    out = [f for f in os.listdir(ROOT) if f.endswith(".html") and f not in NOINDEX]
    return sorted(out, key=lambda f: (-float(PRIORITY.get(f, DEFAULT_PRIORITY)[0]), f))


def url_for(page):
    return f"{ORIGIN}/" if page == "index.html" else f"{ORIGIN}/{page}"


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    with open(os.path.join(ROOT, path), "w", encoding="utf-8") as fh:
        fh.write(text)


def find(pattern, html, what, page, required=True):
    m = re.search(pattern, html, re.S | re.I)
    if not m:
        if required:
            sys.exit(f"gen_seo: no {what} found in {page}")
        return ""
    return m.group(1).strip()


def unescape(text):
    return (text.replace("&amp;", "&").replace("&#39;", "'").replace("&quot;", '"')
                .replace("&lt;", "<").replace("&gt;", ">").replace("&mdash;", "—"))


def esc(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace('"', "&quot;"))


def last_modified(page):
    """Real content date: last git commit touching the file, else mtime."""
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", page],
                             cwd=ROOT, capture_output=True, text=True, timeout=15)
        stamp = out.stdout.strip()
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", stamp):
            return stamp
    except Exception:
        pass
    return datetime.fromtimestamp(os.path.getmtime(os.path.join(ROOT, page)),
                                  timezone.utc).strftime("%Y-%m-%d")


def head_block(page, title, description, noindex):
    url = url_for(page)
    lines = [START, f'<link rel="canonical" href="{url}">']
    if noindex:
        lines.append('<meta name="robots" content="noindex, follow">')
    lines += [
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{esc(SITE_NAME)}">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(description)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{OG_IMAGE}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta property="og:image:alt" content="Move to Huntsville — relocation data for Huntsville, Alabama">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(title)}">',
        f'<meta name="twitter:description" content="{esc(description)}">',
        f'<meta name="twitter:image" content="{OG_IMAGE}">',
    ]
    if not noindex:
        lines.append(json_ld(page, title, description, url))
    lines.append(END)
    return "\n".join(lines)


def json_ld(page, title, description, url):
    site = {"@type": "WebSite", "@id": f"{ORIGIN}/#website", "url": f"{ORIGIN}/",
            "name": SITE_NAME, "inLanguage": "en-US",
            "publisher": {"@id": f"{ORIGIN}/#organization"}}
    if page == "index.html":
        graph = [
            {"@type": "Organization", "@id": f"{ORIGIN}/#organization",
             "name": SITE_NAME, "url": f"{ORIGIN}/",
             "logo": {"@type": "ImageObject",
                      "url": f"{ORIGIN}/assets/img/logo/png/logo-horizontal-520.png",
                      "width": 520},
             "areaServed": {"@type": "Place", "name": "Huntsville, Alabama, USA"}},
            site,
            {"@type": "WebPage", "@id": url, "url": url, "name": title,
             "description": description, "isPartOf": {"@id": f"{ORIGIN}/#website"},
             "primaryImageOfPage": {"@type": "ImageObject", "url": OG_IMAGE}},
        ]
    else:
        graph = [
            site,
            {"@type": "WebPage", "@id": url, "url": url, "name": title,
             "description": description, "isPartOf": {"@id": f"{ORIGIN}/#website"}},
            {"@type": "BreadcrumbList", "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": f"{ORIGIN}/"},
                {"@type": "ListItem", "position": 2, "name": title, "item": url},
            ]},
        ]
    payload = {"@context": "https://schema.org", "@graph": graph}
    return ('<script type="application/ld+json">'
            + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
            + "</script>")


def render_page(page):
    html = read(page)
    noindex = page in NOINDEX
    # 1. drop any previously generated block, 2. drop hand-written head tags we own
    html = re.sub(re.escape(START) + r".*?" + re.escape(END), "", html, flags=re.S)
    head = HEAD.search(html)
    if not head:
        sys.exit(f"gen_seo: no <head> in {page}")
    cleaned = CANONICAL.sub("", OG_META.sub("", head.group(0)))
    html = html[:head.start()] + cleaned + html[head.end():]

    title = unescape(find(r"<title>(.*?)</title>", html, "<title>", page))
    description = unescape(find(r'<meta name="description" content="(.*?)"', html,
                               "meta description", page, required=not noindex))
    # 3. inject the generated block just before </head>. Rebuild that boundary
    # explicitly (rather than string-replacing) so repeated runs converge instead
    # of accumulating blank lines.
    close = html.rfind("</head>")
    return html[:close].rstrip("\n") + "\n" + head_block(page, title, description, noindex) \
        + "\n" + html[close:]


def sitemap():
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    rows = []
    for page in pages():
        priority, changefreq = PRIORITY.get(page, DEFAULT_PRIORITY)
        lastmod = last_modified(page)
        rows.append(f"  <url>\n    <loc>{url_for(page)}</loc>\n"
                    f"    <lastmod>{lastmod}</lastmod>\n"
                    f"    <changefreq>{changefreq}</changefreq>\n"
                    f"    <priority>{priority}</priority>\n  </url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(rows) + "\n</urlset>\n")


def robots():
    return ("# Move to Huntsville — https://www.movetohuntsville.net\n"
            "User-agent: *\n"
            "Allow: /\n"
            "Disallow: /_leads\n"
            "Disallow: /leads.\n"
            "Disallow: /api/\n"
            "Disallow: /logo-preview.html\n"
            "\n"
            f"Sitemap: {ORIGIN}/sitemap.xml\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report drift instead of writing")
    args = ap.parse_args()

    changed = []
    for page in pages() + sorted(NOINDEX):
        new = render_page(page)
        if new != read(page):
            changed.append(page)
            if not args.check:
                write(page, new)
    for name, content in (("robots.txt", robots()), ("sitemap.xml", sitemap())):
        exists = os.path.exists(os.path.join(ROOT, name))
        if not exists or read(name) != content:
            changed.append(name)
            if not args.check:
                write(name, content)

    if args.check and changed:
        sys.exit("gen_seo: out of date: " + ", ".join(changed))
    print(f"{'would update' if args.check else 'updated'}: "
          f"{len(changed)} file(s)" + (f" — {', '.join(changed)}" if changed else ""))


if __name__ == "__main__":
    main()
